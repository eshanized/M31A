import { isApiError, isStructuredError } from './quotaErrorDetection.js';
import { DEFAULT_M31A_MODEL } from '../config/models.js';
import type { UserTierId } from '../config/tierTypes.js';
import { AuthType } from '../core/contentGenerator.js';

const RATE_LIMIT_ERROR_MESSAGE_NVIDIA_NIM =
  '\nNVIDIA NIM rate limit reached. Please wait and try again later, or check your NVIDIA_API_KEY quota.';
const getRateLimitErrorMessageDefault = (
  fallbackModel: string = DEFAULT_M31A_MODEL,
) =>
  `\nPossible quota limitations in place or slow response times detected. Switching to the ${fallbackModel} model for the rest of this session.`;

function getRateLimitMessage(
  authType?: AuthType,
  fallbackModel?: string,
): string {
  switch (authType) {
    case AuthType.USE_NVIDIA_NIM:
      return fallbackModel
        ? getRateLimitErrorMessageDefault(fallbackModel)
        : RATE_LIMIT_ERROR_MESSAGE_NVIDIA_NIM;
    default:
      return getRateLimitErrorMessageDefault(fallbackModel);
  }
}

export function parseAndFormatApiError(
  error: unknown,
  authType?: AuthType,
  userTier?: UserTierId,
  currentModel?: string,
  fallbackModel?: string,
): string {
  if (isStructuredError(error)) {
    let text = `[API Error: ${error.message}]`;
    if (error.status === 429) {
      text += getRateLimitMessage(authType, fallbackModel);
    }
    return text;
  }

  // The error message might be a string containing a JSON object.
  if (typeof error === 'string') {
    const jsonStart = error.indexOf('{');
    if (jsonStart === -1) {
      return `[API Error: ${error}]`; // Not a JSON error, return as is.
    }

    const jsonString = error.substring(jsonStart);

    try {
      const parsedError = JSON.parse(jsonString) as unknown;
      if (isApiError(parsedError)) {
        let finalMessage = parsedError.error.message;
        try {
          // See if the message is a stringified JSON with another error
          const nestedError = JSON.parse(finalMessage) as unknown;
          if (isApiError(nestedError)) {
            finalMessage = nestedError.error.message;
          }
        } catch {
          // It's not a nested JSON error, so we just use the message as is.
        }
        let text = `[API Error: ${finalMessage} (Status: ${parsedError.error.status})]`;
        if (parsedError.error.code === 429) {
          text += getRateLimitMessage(authType, fallbackModel);
        }
        return text;
      }
    } catch {
      // Not a valid JSON, fall through and return the original message.
    }
    return `[API Error: ${error}]`;
  }

  return '[API Error: An unknown error occurred.]';
}
